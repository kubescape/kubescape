package fixhandler

import (
	"fmt"
	"os"
	"path/filepath"
)

// EmitPostRenderer writes executable Helm post-renderer scripts (POSIX bash and Windows batch)
// into outputDir. The script accepts Helm-rendered manifests on stdin, pipes them through Kustomize
// with the patches emitted in kustomizeDir in an isolated workspace, and emits the remediated
// manifests to stdout.
//
// Usage with Helm:
//
//	helm install <release> <chart> --post-renderer <outputDir>/renderer.sh
func EmitPostRenderer(kustomizeDir, outputDir string) error {
	if kustomizeDir == "" {
		return fmt.Errorf("kustomize directory cannot be empty")
	}
	if outputDir == "" {
		return fmt.Errorf("output directory cannot be empty")
	}

	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("failed to create post-renderer directory %q: %w", outputDir, err)
	}

	cleanKustDir, err := filepath.Abs(kustomizeDir)
	if err != nil {
		cleanKustDir = kustomizeDir
	}

	kustBaseName := filepath.Base(cleanKustDir)

	// 1. Generate POSIX Bash post-renderer script
	shContent := fmt.Sprintf(`#!/usr/bin/env bash
# Auto-generated by Kubescape fix --output-post-renderer
# Usage: helm install <release> <chart> --post-renderer %s/renderer.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KUST_DIR=%q

# If KUST_DIR is not found at original absolute path, check relative to this script
if [ ! -d "$KUST_DIR" ]; then
  if [ -f "$SCRIPT_DIR/kustomization.yaml" ]; then
    KUST_DIR="$SCRIPT_DIR"
  elif [ -d "$SCRIPT_DIR/%s" ]; then
    KUST_DIR="$SCRIPT_DIR/%s"
  fi
fi

if ! command -v kustomize >/dev/null 2>&1; then
  echo "[error] kustomize executable not found in PATH" >&2
  exit 1
fi

# Create an isolated temporary workspace for this execution
WORK_DIR=$(mktemp -d 2>/dev/null || mktemp -d -t 'kust-helm-renderer')
trap 'rm -rf "$WORK_DIR"' EXIT

# Read Helm-rendered manifests from stdin
cat > "$WORK_DIR/all.yaml"

# Construct a transient kustomization referencing all.yaml as the sole base resource
cat << 'EOF' > "$WORK_DIR/kustomization.yaml"
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - all.yaml
EOF

# Copy only the patch definitions from the kustomize directory
if [ -f "$KUST_DIR/kustomization.yaml" ]; then
  # Extract patches block from kustomization.yaml and append to transient kustomization
  sed -n '/^patches:/,$p' "$KUST_DIR/kustomization.yaml" >> "$WORK_DIR/kustomization.yaml"
  # Copy patch files into the isolated workspace
  find "$KUST_DIR" -maxdepth 1 \( -name "*.yaml" -o -name "*.json" \) ! -name "base.yaml" ! -name "kustomization.yaml" -exec cp {} "$WORK_DIR/" \;
fi

# Execute kustomize build and emit remediated YAML directly to stdout
kustomize build "$WORK_DIR"
`, outputDir, cleanKustDir, kustBaseName, kustBaseName)

	shPath := filepath.Join(outputDir, "renderer.sh")
	if err := os.WriteFile(shPath, []byte(shContent), 0755); err != nil {
		return fmt.Errorf("failed to write post-renderer script %q: %w", shPath, err)
	}

	// 2. Generate Windows batch script (renderer.bat)
	batContent := fmt.Sprintf(`@echo off
REM Auto-generated by Kubescape fix --output-post-renderer
setlocal enabledelayedexpansion

set "SCRIPT_DIR=%%~dp0"
set "KUST_DIR=%s"

if not exist "!KUST_DIR!" (
  if exist "!SCRIPT_DIR!kustomization.yaml" (
    set "KUST_DIR=!SCRIPT_DIR!"
  ) else if exist "!SCRIPT_DIR!%s" (
    set "KUST_DIR=!SCRIPT_DIR!%s"
  )
)

where kustomize >nul 2>nul
if %%ERRORLEVEL%% neq 0 (
  echo [error] kustomize executable not found in PATH >&2
  exit /b 1
)

set "WORK_DIR=%%TEMP%%\kust-helm-%%RANDOM%%"
mkdir "!WORK_DIR!" >nul 2>nul

REM Stream stdin to all.yaml
findstr "^" > "!WORK_DIR!\all.yaml"

REM Construct transient kustomization.yaml
(
echo apiVersion: kustomize.config.k8s.io/v1beta1
echo kind: Kustomization
echo resources:
echo   - all.yaml
) > "!WORK_DIR!\kustomization.yaml"

if exist "!KUST_DIR!\kustomization.yaml" (
  copy /y "!KUST_DIR!\*.yaml" "!WORK_DIR!\" >nul 2>nul
  copy /y "!KUST_DIR!\*.json" "!WORK_DIR!\" >nul 2>nul
  del /q "!WORK_DIR!\base.yaml" >nul 2>nul
  powershell -NoProfile -Command "Get-Content '!KUST_DIR!\kustomization.yaml' | Select-String -Pattern '^patches:' -Context 0, 10000 | ForEach-Object { $_.Line; $_.Context.PostContext } | Add-Content '!WORK_DIR!\kustomization.yaml'" >nul 2>nul
)

kustomize build "!WORK_DIR!"
set EXIT_CODE=%%ERRORLEVEL%%

rd /s /q "!WORK_DIR!" >nul 2>nul
exit /b %%EXIT_CODE%%
`, cleanKustDir, kustBaseName, kustBaseName)

	batPath := filepath.Join(outputDir, "renderer.bat")
	if err := os.WriteFile(batPath, []byte(batContent), 0755); err != nil {
		return fmt.Errorf("failed to write Windows post-renderer script %q: %w", batPath, err)
	}

	return nil
}
