package fixhandler

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"unicode"
)

// isSafeScriptPath validates that a directory path can be safely emitted into
// generated shell and batch script templates. It rejects newlines, carriage
// returns, control characters, and double quotes, which could break out of
// command comments or variable assignments in bash or cmd.exe batch scripts.
func isSafeScriptPath(path string) bool {
	for _, r := range path {
		if r == '"' || r == '\n' || r == '\r' || r == 0 || unicode.IsControl(r) {
			return false
		}
	}
	return true
}

// shQuote escapes a string for safe usage in POSIX shells (bash) by wrapping in single quotes
// and escaping existing single quotes as '\”.
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// batEscape escapes a value for a quoted `set "NAME=value"` line that renderer.bat
// runs with delayed expansion disabled. There only % is special and is written %%:
// ! and ^ are literal inside the quotes. They would not be once delayed expansion
// is on, which is why the values are set before it is enabled and read back with
// !NAME!, whose expanded text cmd does not parse again.
func batEscape(s string) string {
	return strings.ReplaceAll(s, "%", "%%")
}

// writeRestrictedScript writes executable script data to filename within root with 0755 permissions.
// It uses os.Root containment and rejects symbolic links to prevent escaping outputDir.
func writeRestrictedScript(root *os.Root, filename string, data []byte) error {
	// Reject symlinks before writing to guarantee containment and preserve external targets.
	if fi, err := root.Lstat(filename); err == nil && (fi.Mode()&os.ModeSymlink != 0) {
		return fmt.Errorf("refusing to write script %q: target is a symbolic link", filename)
	}

	file, err := root.OpenFile(filename, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0755) // #nosec G306 -- generated script requires executable permissions (0755)
	if err != nil {
		return err
	}
	if err := file.Chmod(0755); err != nil { // #nosec G302 -- generated script requires executable permissions (0755)
		_ = file.Close()
		return err
	}
	if _, err := file.Write(data); err != nil {
		_ = file.Close()
		return err
	}
	return file.Close()
}

// EmitPostRenderer writes executable Helm post-renderer scripts (POSIX bash and Windows batch)
// into outputDir. The script accepts Helm-rendered manifests on stdin, pipes them through Kustomize
// with the patches emitted in kustomizeDir in an isolated workspace, and emits the remediated
// manifests to stdout.
//
// Usage with Helm:
//
//	helm install <release> <chart> --post-renderer <outputDir>/renderer.sh
func EmitPostRenderer(kustomizeDir, outputDir string) error {
	if kustomizeDir == "" {
		return fmt.Errorf("kustomize directory cannot be empty")
	}
	if !isSafeScriptPath(kustomizeDir) {
		return fmt.Errorf("kustomize directory %q contains unsafe characters", kustomizeDir)
	}
	if outputDir == "" {
		return fmt.Errorf("output directory cannot be empty")
	}
	if !isSafeScriptPath(outputDir) {
		return fmt.Errorf("output directory %q contains unsafe characters", outputDir)
	}

	cleanKustDir, err := filepath.Abs(kustomizeDir)
	if err != nil {
		cleanKustDir = kustomizeDir
	}
	if !isSafeScriptPath(cleanKustDir) {
		return fmt.Errorf("resolved kustomize directory %q contains unsafe characters", cleanKustDir)
	}

	cleanOutputDir, err := filepath.Abs(outputDir)
	if err != nil {
		cleanOutputDir = outputDir
	}
	if !isSafeScriptPath(cleanOutputDir) {
		return fmt.Errorf("resolved output directory %q contains unsafe characters", cleanOutputDir)
	}

	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("failed to create post-renderer directory %q: %w", outputDir, err)
	}

	root, err := os.OpenRoot(outputDir)
	if err != nil {
		return fmt.Errorf("failed to open output directory %q: %w", outputDir, err)
	}
	defer root.Close()

	kustBaseName := filepath.Base(cleanKustDir)

	// 1. Generate POSIX Bash post-renderer script
	shContent := fmt.Sprintf(`#!/usr/bin/env bash
# Auto-generated by Kubescape fix --output-post-renderer
# Usage: helm install <release> <chart> --post-renderer %s/renderer.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KUST_DIR=%s

# If KUST_DIR is not found at original absolute path, check relative to this script
if [ ! -d "$KUST_DIR" ]; then
  if [ -f "$SCRIPT_DIR/kustomization.yaml" ]; then
    KUST_DIR="$SCRIPT_DIR"
  elif [ -d "$SCRIPT_DIR"/%s ]; then
    KUST_DIR="$SCRIPT_DIR"/%s
  fi
fi

if ! command -v kustomize >/dev/null 2>&1; then
  echo "[error] kustomize executable not found in PATH" >&2
  exit 1
fi

# Create an isolated temporary workspace for this execution
WORK_DIR=$(mktemp -d 2>/dev/null || mktemp -d -t 'kust-helm-renderer')
trap 'rm -rf "$WORK_DIR"' EXIT

# Read Helm-rendered manifests from stdin
cat > "$WORK_DIR/all.yaml"

# Construct a transient kustomization referencing all.yaml as the sole base resource
cat << 'EOF' > "$WORK_DIR/kustomization.yaml"
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - all.yaml
EOF

# Copy only the patch definitions from the kustomize directory
if [ -f "$KUST_DIR/kustomization.yaml" ]; then
  # Extract patches block from kustomization.yaml and append to transient kustomization
  sed -n '/^patches:/,$p' "$KUST_DIR/kustomization.yaml" >> "$WORK_DIR/kustomization.yaml"
  # Copy patch files into the isolated workspace, excluding all.yaml, base.yaml, and kustomization.yaml
  find "$KUST_DIR" -maxdepth 1 \( -name "*.yaml" -o -name "*.json" \) ! -name "all.yaml" ! -name "base.yaml" ! -name "kustomization.yaml" -exec cp {} "$WORK_DIR/" \;
  if ! grep -q "^patches:" "$WORK_DIR/kustomization.yaml"; then
    echo "[error] no patches found in $KUST_DIR/kustomization.yaml; refusing to emit unpatched manifests" >&2
    exit 1
  fi
else
  echo "[error] kustomization.yaml not found in $KUST_DIR; refusing to emit unpatched manifests" >&2
  exit 1
fi

# Execute kustomize build and emit remediated YAML directly to stdout
kustomize build "$WORK_DIR"
`, outputDir, shQuote(cleanKustDir), shQuote(kustBaseName), shQuote(kustBaseName))

	if err := writeRestrictedScript(root, "renderer.sh", []byte(shContent)); err != nil {
		return fmt.Errorf("failed to write post-renderer script \"renderer.sh\": %w", err)
	}

	// 2. Generate Windows batch script (renderer.bat)
	batContent := fmt.Sprintf(`@echo off
REM Auto-generated by Kubescape fix --output-post-renderer
setlocal disabledelayedexpansion

set "SCRIPT_DIR=%%~dp0"
set "KUST_DIR=%s"
set "KUST_BASE=%s"
setlocal enabledelayedexpansion

if not exist "!KUST_DIR!" (
  if exist "!SCRIPT_DIR!kustomization.yaml" (
    set "KUST_DIR=!SCRIPT_DIR!"
  ) else if exist "!SCRIPT_DIR!!KUST_BASE!" (
    set "KUST_DIR=!SCRIPT_DIR!!KUST_BASE!"
  )
)

where kustomize >nul 2>nul
if %%ERRORLEVEL%% neq 0 (
  echo [error] kustomize executable not found in PATH >&2
  exit /b 1
)

REM Create an exclusive temporary workspace with collision retry
set "WORK_DIR="
for /L %%%%I in (1,1,50) do (
  if not defined WORK_DIR (
    set "CANDIDATE=%%TEMP%%\kust-helm-!RANDOM!-!RANDOM!-%%%%I"
    2>nul (
      mkdir "!CANDIDATE!" && set "WORK_DIR=!CANDIDATE!"
    )
  )
)

if not defined WORK_DIR (
  echo [error] failed to create exclusive temporary workspace in %%TEMP%% >&2
  exit /b 1
)

REM Stream stdin as raw binary bytes to all.yaml without line-length truncation
powershell -NoProfile -Command "$w = Join-Path $env:WORK_DIR 'all.yaml'; $in = [Console]::OpenStandardInput(); $out = [System.IO.File]::Create($w); try { $in.CopyTo($out) } catch { exit 1 } finally { $out.Close(); $in.Close() }"
if errorlevel 1 (
  echo [error] failed to read Helm manifest stream from stdin >&2
  rd /s /q "!WORK_DIR!" >nul 2>nul
  exit /b 1
)

if not exist "!KUST_DIR!\kustomization.yaml" (
  echo [error] kustomization.yaml not found in !KUST_DIR!; refusing to emit unpatched manifests >&2
  rd /s /q "!WORK_DIR!" >nul 2>nul
  exit /b 1
)

powershell -NoProfile -Command "Get-ChildItem -LiteralPath $env:KUST_DIR -File | Where-Object { ($_.Extension -eq '.yaml' -or $_.Extension -eq '.json') -and (@('all.yaml','base.yaml','kustomization.yaml') -notcontains $_.Name) } | Copy-Item -Destination $env:WORK_DIR -Force" >nul 2>nul

REM Construct transient kustomization.yaml (after copy so all.yaml reference is not overwritten)
(
echo apiVersion: kustomize.config.k8s.io/v1beta1
echo kind: Kustomization
echo resources:
echo   - all.yaml
) > "!WORK_DIR!\kustomization.yaml"

powershell -NoProfile -Command "$k = Join-Path $env:KUST_DIR 'kustomization.yaml'; $w = Join-Path $env:WORK_DIR 'kustomization.yaml'; Get-Content -LiteralPath $k | Select-String -Pattern '^patches:' -Context 0, 10000 | ForEach-Object { $_.Line; $_.Context.PostContext } | Add-Content -LiteralPath $w" >nul 2>nul
if errorlevel 1 (
  echo [error] failed to extract patches from kustomization.yaml; refusing to emit unpatched manifests >&2
  rd /s /q "!WORK_DIR!" >nul 2>nul
  exit /b 1
)

findstr /b "patches:" "!WORK_DIR!\kustomization.yaml" >nul 2>nul
if errorlevel 1 (
  echo [error] no patches found in kustomization.yaml; refusing to emit unpatched manifests >&2
  rd /s /q "!WORK_DIR!" >nul 2>nul
  exit /b 1
)

kustomize build "!WORK_DIR!"
set EXIT_CODE=%%ERRORLEVEL%%

rd /s /q "!WORK_DIR!" >nul 2>nul
exit /b %%EXIT_CODE%%
`, batEscape(cleanKustDir), batEscape(kustBaseName))

	if err := writeRestrictedScript(root, "renderer.bat", []byte(batContent)); err != nil {
		return fmt.Errorf("failed to write Windows post-renderer script \"renderer.bat\": %w", err)
	}

	return nil
}
