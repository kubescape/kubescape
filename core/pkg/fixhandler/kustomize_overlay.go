// kustomizationCandidates lists the standard filenames Kustomize looks for.
var kustomizationCandidates = []string{"kustomization.yaml", "kustomization.yml", "Kustomization"}

// findKustomizationFile searches dir for a valid kustomization file.
func findKustomizationFile(dir string) string {
	for _, candidate := range kustomizationCandidates {
		p := filepath.Join(dir, candidate)
		info, err := os.Stat(p)
		if err == nil && !info.IsDir() {
			return p
		}
	}
	return ""
}

// resolveKustomizeOverlaySource resolves the source information for a resource
// generated by a Kustomize overlay. It verifies directory containment and ensures
// the overlay kustomization file exists.
func (h *FixHandler) resolveKustomizeOverlaySource(ctx context.Context, resourceObj *reporthandling.Resource, reportedPath string) resourceSource {
	src := resourceSource{
		reportedPath: reportedPath,
	}

	overlayDir := resourceObj.Source.KustomizeDirectoryName
	if overlayDir == "" {
		src.skipReason = "skipped: kustomize directory not specified"
		return src
	}

	basePath := h.resourceBasePath(resourceObj)
	candidateOverlay := overlayDir
	if !filepath.IsAbs(candidateOverlay) {
		candidateOverlay = filepath.Join(basePath, candidateOverlay)
	}
	candidateOverlay = filepath.Clean(candidateOverlay)

	if !isPathContained(basePath, candidateOverlay) {
		logger.L().Ctx(ctx).Warning("Skipping kustomize overlay directory that escapes scanned directory: " + sanitizeForLog(candidateOverlay))
		src.skipReason = "skipped: kustomize overlay directory escapes scanned directory"
		return src
	}

	kustFile := findKustomizationFile(candidateOverlay)
	if kustFile == "" {
		logger.L().Ctx(ctx).Warning("Skipping missing kustomization file in directory: " + sanitizeForLog(candidateOverlay))
		src.skipReason = "skipped: kustomization file not found"
		return src
	}

	src.isKustomizeOverlay = true
	src.kustomizeOverlayDir = candidateOverlay
	src.filePath = kustFile
	rel, err := filepath.Rel(basePath, kustFile)
	if err == nil {
		src.relativePath = rel
	} else {
		src.relativePath = kustFile
	}
	src.documentIndex = 0
	return src
}

// overlayPatchFileName generates a unique, collision-proof filename for a resource patch.
func overlayPatchFileName(resource *reporthandling.Resource, target ...kustomizeTarget) string {
	group, version := parseGroupVersion(resource.GetApiVersion())
	name := resource.GetName()
	namespace := resource.GetNamespace()
	if len(target) > 0 && target[0].Name != "" {
		name = target[0].Name
		namespace = target[0].Namespace
	}
	key := resourceKey{
		Group:     group,
		Version:   version,
		Kind:      resource.GetKind(),
		Namespace: namespace,
		Name:      name,
	}
	return resourcePatchFilename(key)
}

// compareFixPaths compares two fix paths segment-by-segment.
// Array indices are compared numerically (e.g. args[0] before args[1])
// so that array additions can be resolved without triggering array gap errors.
func compareFixPaths(pathA, pathB string) bool {
	partsA, errA := parseYAMLPath(pathA)
	partsB, errB := parseYAMLPath(pathB)
	if errA != nil || errB != nil {
		return pathA < pathB
	}

	minLen := len(partsA)
	if len(partsB) < minLen {
		minLen = len(partsB)
	}

	for i := 0; i < minLen; i++ {
		pA, pB := partsA[i], partsB[i]
		if pA.sequence && pB.sequence {
			if pA.index != pB.index {
				return pA.index < pB.index
			}
		} else if !pA.sequence && !pB.sequence {
			if pA.key != pB.key {
				return pA.key < pB.key
			}
		} else {
			return pA.sequence
		}
	}

	return len(partsA) < len(partsB)
}

// buildOverlayPatchForResource compiles all FixPaths for a resource into RFC 6902 patch operations.
func buildOverlayPatchForResource(fix ResourceFixInfo) ([]kustomizePatchOp, error) {
	if fix.Resource == nil {
		return nil, errors.New("resource is nil")
	}

	workingObj := deepCopyMap(fix.Resource.GetObject())

	exprKeys := make([]string, 0, len(fix.YamlExpressions))
	for k := range fix.YamlExpressions {
		exprKeys = append(exprKeys, k)
	}
	sort.SliceStable(exprKeys, func(i, j int) bool {
		return compareFixPaths(exprKeys[i], exprKeys[j])
	})

	var concreteFixPaths []armotypes.FixPath
	for _, key := range exprKeys {
		fp := fix.YamlExpressions[key]
		if fp.Path == "" {
			continue
		}
		expanded := expandWildcardFixPaths(workingObj, fp)
		concreteFixPaths = append(concreteFixPaths, expanded...)
	}

	// Sort concreteFixPaths so indexed additions (e.g. args[0], args[1]) are resolved in order
	sort.SliceStable(concreteFixPaths, func(i, j int) bool {
		return compareFixPaths(concreteFixPaths[i].Path, concreteFixPaths[j].Path)
	})

	var ops []kustomizePatchOp
	for _, fp := range concreteFixPaths {
		patchOps, err := resolveFixPathOps(workingObj, fp)
		if err != nil {
			return nil, err
		}
		ops = append(ops, patchOps...)
	}
	return ops, nil
}

// mergePatchOps combines existing JSON 6902 patch operations with new operations.
// If an operation targets the same path, the new operation replaces the existing one.
// New paths are appended, preserving the order of existing operations.
func mergePatchOps(existing, newOps []kustomizePatchOp) []kustomizePatchOp {
	if len(existing) == 0 {
		return newOps
	}
	if len(newOps) == 0 {
		return existing
	}

	merged := make([]kustomizePatchOp, len(existing))
	copy(merged, existing)

	pathToIdx := make(map[string]int, len(existing))
	for i, op := range merged {
		pathToIdx[op.Path] = i
	}

	for _, op := range newOps {
		if idx, exists := pathToIdx[op.Path]; exists {
			merged[idx] = op
		} else {
			pathToIdx[op.Path] = len(merged)
			merged = append(merged, op)
		}
	}

	return merged
}

// addPatchToKustomizationYAML parses kustomization.yaml preserving comments and formatting,
// and appends a surgical patch entry under patches: if not already present.
// It constructs the entry using yaml.Node to avoid type ambiguity for names like "123" or "true",
// and escapes the target name and namespace with regexp.QuoteMeta.
func addPatchToKustomizationYAML(kustContent string, patchRelPath string, target kustomizeTarget) (string, error) {
	var node yaml.Node
	if err := yaml.Unmarshal([]byte(kustContent), &node); err != nil {
		return "", fmt.Errorf("failed to parse kustomization yaml: %w", err)
	}
	if len(node.Content) == 0 {
		return "", errors.New("empty kustomization yaml")
	}

	doc := node.Content[0]
	if doc.Kind != yaml.MappingNode {
		return "", errors.New("kustomization yaml root is not a mapping")
	}

	var patchesNode *yaml.Node
	matchCount := 0
	for i := 0; i < len(doc.Content)-1; i += 2 {
		if strings.EqualFold(doc.Content[i].Value, "patches") {
			matchCount++
			patchesNode = doc.Content[i+1]
		}
	}

	if matchCount > 1 {
		return "", errors.New("kustomization yaml has multiple case-insensitive 'patches' fields")
	}

	if patchesNode != nil && (patchesNode.Tag == "!!null" || (patchesNode.Kind == yaml.ScalarNode && (patchesNode.Value == "" || patchesNode.Value == "null" || patchesNode.Value == "~"))) {
		patchesNode.Kind = yaml.SequenceNode
		patchesNode.Tag = "!!seq"
		patchesNode.Value = ""
		patchesNode.Content = nil
	}

	if patchesNode != nil && patchesNode.Kind != yaml.SequenceNode {
		return "", errors.New("'patches' field in kustomization yaml is not a sequence")
	}

	if patchesNode == nil {
		keyNode := &yaml.Node{
			Kind:  yaml.ScalarNode,
			Tag:   "!!str",
			Value: "patches",
		}
		valNode := &yaml.Node{
			Kind: yaml.SequenceNode,
			Tag:  "!!seq",
		}
		doc.Content = append(doc.Content, keyNode, valNode)
		patchesNode = valNode
	}

	// Normalize patchRelPath to forward slashes for Kustomize compatibility across OSes
	patchRelPathSlash := filepath.ToSlash(patchRelPath)

	// Check if already present to ensure idempotency
	for _, item := range patchesNode.Content {
		if item.Kind == yaml.MappingNode {
			for j := 0; j < len(item.Content); j += 2 {
				if item.Content[j].Value == "path" && (item.Content[j+1].Value == patchRelPath || item.Content[j+1].Value == patchRelPathSlash) {
					return kustContent, nil
				}
			}
		}
	}

	targetMap := &yaml.Node{
		Kind: yaml.MappingNode,
		Tag:  "!!map",
	}
	if target.Kind != "" {
		targetMap.Content = append(targetMap.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: "kind"},
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: target.Kind},
		)
	}
	if target.Name != "" {
		targetMap.Content = append(targetMap.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: "name"},
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: regexp.QuoteMeta(target.Name)},
		)
	}
	if target.Namespace != "" {
		targetMap.Content = append(targetMap.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: "namespace"},
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: regexp.QuoteMeta(target.Namespace)},
		)
	}

	entryNode := &yaml.Node{
		Kind: yaml.MappingNode,
		Tag:  "!!map",
		Content: []*yaml.Node{
			{Kind: yaml.ScalarNode, Tag: "!!str", Value: "path"},
			{Kind: yaml.ScalarNode, Tag: "!!str", Value: patchRelPathSlash},
			{Kind: yaml.ScalarNode, Tag: "!!str", Value: "target"},
			targetMap,
		},
	}

	patchesNode.Content = append(patchesNode.Content, entryNode)

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&node); err != nil {
		return "", fmt.Errorf("failed to encode kustomization yaml: %w", err)
	}

	return buf.String(), nil
}

type kustomizationMeta struct {
	NamePrefix string `yaml:"namePrefix"`
	NameSuffix string `yaml:"nameSuffix"`
	Namespace  string `yaml:"namespace"`
}

// tryResolveOriginManifest attempts to find and inspect the origin resource manifest on disk
// to extract its original unadorned metadata.name and metadata.namespace before overlay transformations.
func tryResolveOriginManifest(fix ResourceFixInfo, kustMeta kustomizationMeta) (string, string, bool) {
	var candidates []string
	if fix.reportedPath != "" {
		candidates = append(candidates, fix.reportedPath)
	}
	if fix.Resource != nil && fix.Resource.Source != nil {
		if fix.Resource.Source.Path != "" && fix.Resource.Source.RelativePath != "" {
			candidates = append(candidates, filepath.Join(fix.Resource.Source.Path, fix.Resource.Source.RelativePath))
		}
	}

	targetKind := ""
	renderedName := ""
	if fix.Resource != nil {
		targetKind = fix.Resource.GetKind()
		renderedName = fix.Resource.GetName()
	}

	for _, cand := range candidates {
		if cand == "" {
			continue
		}
		data, err := readManifestFile(cand)
		if err != nil {
			continue
		}

		decoder := yaml.NewDecoder(bytes.NewReader(data))
		for {
			var doc struct {
				Kind     string `yaml:"kind"`
				Metadata struct {
					Name      string `yaml:"name"`
					Namespace string `yaml:"namespace"`
				} `yaml:"metadata"`
			}
			if err := decoder.Decode(&doc); err != nil {
				break
			}
			if doc.Kind != targetKind {
				continue
			}

			expectedRendered := kustMeta.NamePrefix + doc.Metadata.Name + kustMeta.NameSuffix
			if doc.Metadata.Name == renderedName || expectedRendered == renderedName {
				return doc.Metadata.Name, doc.Metadata.Namespace, true
			}
		}
	}

	return "", "", false
}

// resolveTargetIdentity resolves the resource's kind, name, and namespace at the Kustomize patches stage.
// Because Kustomize applies patches before applying transformers like namePrefix, nameSuffix, and namespace,
// an overlay target must select against the pre-transformation identity. If identity cannot be resolved,
// it returns an error reporting the fix as unsupported.
func resolveTargetIdentity(overlayDir string, kustMeta kustomizationMeta, fix ResourceFixInfo) (kustomizeTarget, error) {
	renderedKind := fix.Resource.GetKind()
	renderedName := fix.Resource.GetName()
	renderedNamespace := fix.Resource.GetNamespace()

	// 1. Try to resolve from origin manifest on disk if available
	if name, ns, ok := tryResolveOriginManifest(fix, kustMeta); ok {
		return kustomizeTarget{
			Kind:      renderedKind,
			Name:      name,
			Namespace: ns,
		}, nil
	}

	// 2. Resolve by stripping overlay transformations
	targetName := renderedName
	if kustMeta.NamePrefix != "" {
		if !strings.HasPrefix(targetName, kustMeta.NamePrefix) {
			return kustomizeTarget{}, fmt.Errorf("unsupported: cannot resolve resource identity at Kustomize patches stage: resource %s/%s does not match overlay namePrefix %q", renderedKind, renderedName, kustMeta.NamePrefix)
		}
		targetName = strings.TrimPrefix(targetName, kustMeta.NamePrefix)
	}

	if kustMeta.NameSuffix != "" {
		if !strings.HasSuffix(targetName, kustMeta.NameSuffix) {
			return kustomizeTarget{}, fmt.Errorf("unsupported: cannot resolve resource identity at Kustomize patches stage: resource %s/%s does not match overlay nameSuffix %q", renderedKind, renderedName, kustMeta.NameSuffix)
		}
		targetName = strings.TrimSuffix(targetName, kustMeta.NameSuffix)
	}

	if targetName == "" {
		return kustomizeTarget{}, fmt.Errorf("unsupported: cannot resolve resource identity at Kustomize patches stage: empty resource name after stripping prefix/suffix from %s/%s", renderedKind, renderedName)
	}

	targetNamespace := renderedNamespace
	if kustMeta.Namespace != "" && targetNamespace == kustMeta.Namespace {
		// The rendered namespace was injected by the overlay's namespace transformer.
		// At the patches stage, before transformers run, the resource does not have this overlay namespace.
		targetNamespace = ""
	}

	return kustomizeTarget{
		Kind:      renderedKind,
		Name:      targetName,
		Namespace: targetNamespace,
	}, nil
}

type overlayPatchItem struct {
	fileName        string
	relPathInKust   string
	target          kustomizeTarget
	originalContent string
	updatedContent  string
	ops             []kustomizePatchOp
	isNewFile       bool
}

type overlayFixPlan struct {
	overlayDir   string
	kustFile     string
	kustFileName string
	originalKust string
	updatedKust  string
	patches      []overlayPatchItem
}

// planOverlayChanges inspects the overlay directory and produces an execution plan.
// It uses os.OpenRoot to confine file operations to the overlay directory and rejects
// non-regular kustomization files. Existing patch files are read and merged with new ops.
func planOverlayChanges(overlayDir string, fixes []ResourceFixInfo) (*overlayFixPlan, error) {
	cleanOverlay := filepath.Clean(overlayDir)
	root, err := os.OpenRoot(cleanOverlay)
	if err != nil {
		return nil, fmt.Errorf("failed to open overlay directory %s: %w", cleanOverlay, err)
	}
	defer root.Close()

	var kustFileName string
	for _, candidate := range kustomizationCandidates {
		st, err := root.Stat(candidate)
		if err == nil {
			if st.IsDir() {
				return nil, fmt.Errorf("%q is a directory, not a file: %w", candidate, ErrManifestNotRegular)
			}
			if !st.Mode().IsRegular() {
				return nil, fmt.Errorf("%w: %q", ErrManifestNotRegular, candidate)
			}
			kustFileName = candidate
			break
		}
	}
	if kustFileName == "" {
		return nil, fmt.Errorf("kustomization file not found in %s", cleanOverlay)
	}

	kustBytes, err := readRegularFileFromRoot(root, kustFileName, filepath.Join(cleanOverlay, kustFileName))
	if err != nil {
		return nil, fmt.Errorf("failed to read %s in %s: %w", kustFileName, cleanOverlay, err)
	}

	var kustMeta kustomizationMeta
	_ = yaml.Unmarshal(kustBytes, &kustMeta)

	plan := &overlayFixPlan{
		overlayDir:   cleanOverlay,
		kustFile:     filepath.Join(cleanOverlay, kustFileName),
		kustFileName: kustFileName,
		originalKust: string(kustBytes),
		updatedKust:  string(kustBytes),
	}

	for _, fix := range fixes {
		if fix.Resource == nil {
			continue
		}
		ops, err := buildOverlayPatchForResource(fix)
		if err != nil {
			return nil, fmt.Errorf("failed to build patch for %s/%s: %w", fix.Resource.GetKind(), fix.Resource.GetName(), err)
		}
		if len(ops) == 0 {
			continue
		}

		target, err := resolveTargetIdentity(plan.overlayDir, kustMeta, fix)
		if err != nil {
			return nil, err
		}

		patchFileName := overlayPatchFileName(fix.Resource, target)
		relPatchPath := filepath.Join("patches", patchFileName)

		// Check if we already planned ops for this patch file in the current run
		var existingOps []kustomizePatchOp
		var originalContent string
		var isNewFile = true
		existingIdx := -1
		for idx, p := range plan.patches {
			if p.fileName == patchFileName {
				existingIdx = idx
				existingOps = p.ops
				originalContent = p.originalContent
				isNewFile = p.isNewFile
				break
			}
		}

		if existingIdx == -1 {
			existingBytes, err := readRegularFileFromRoot(root, relPatchPath, filepath.Join(plan.overlayDir, relPatchPath))
			if err != nil {
				if !errors.Is(err, os.ErrNotExist) {
					return nil, fmt.Errorf("failed to read existing patch %s in %s: %w", relPatchPath, plan.overlayDir, err)
				}
			} else {
				isNewFile = false
				originalContent = string(existingBytes)
				if err := yaml.Unmarshal(existingBytes, &existingOps); err != nil {
					return nil, fmt.Errorf("failed to parse existing patch %s in %s: %w", relPatchPath, plan.overlayDir, err)
				}
			}
		}

		mergedOps := mergePatchOps(existingOps, ops)
		mergedBytes, err := yaml.Marshal(mergedOps)
		if err != nil {
			return nil, fmt.Errorf("failed to marshal patch ops for %s: %w", patchFileName, err)
		}

		patchRelPath := filepath.ToSlash(filepath.Join("patches", patchFileName))
		updatedKust, err := addPatchToKustomizationYAML(plan.updatedKust, patchRelPath, target)
		if err != nil {
			return nil, fmt.Errorf("failed to update %s: %w", kustFileName, err)
		}
		plan.updatedKust = updatedKust

		item := overlayPatchItem{
			fileName:        patchFileName,
			relPathInKust:   patchRelPath,
			target:          target,
			originalContent: originalContent,
			updatedContent:  string(mergedBytes),
			ops:             mergedOps,
			isNewFile:       isNewFile,
		}

		if existingIdx >= 0 {
			plan.patches[existingIdx] = item
		} else {
			plan.patches = append(plan.patches, item)
		}
	}

	return plan, nil
}

// applyKustomizeOverlayChanges applies the planned overlay changes.
// When output is nil, changes are written in-place confined via os.OpenRoot.
// When output is non-nil, changes are written under destOverlayDir in the output tree.
func applyKustomizeOverlayChanges(ctx context.Context, plan *overlayFixPlan, output *outputTree, destOverlayDir string) error {
	if len(plan.patches) == 0 && plan.updatedKust == plan.originalKust {
		return nil
	}

	if output != nil {
		for _, patch := range plan.patches {
			destPatchPath := filepath.Join(destOverlayDir, "patches", patch.fileName)
			if err := output.write(destPatchPath, patch.updatedContent, 0600); err != nil {
				return fmt.Errorf("failed to write patch file %s: %w", destPatchPath, err)
			}
		}
		if plan.updatedKust != plan.originalKust {
			destKustPath := filepath.Join(destOverlayDir, plan.kustFileName)
			if err := output.write(destKustPath, plan.updatedKust, 0600); err != nil {
				return fmt.Errorf("failed to write %s: %w", destKustPath, err)
			}
		}
		return nil
	}

	root, err := os.OpenRoot(plan.overlayDir)
	if err != nil {
		return fmt.Errorf("failed to open overlay directory %s: %w", plan.overlayDir, err)
	}
	defer root.Close()

	if st, err := root.Stat("patches"); err != nil {
		if err := root.Mkdir("patches", 0755); err != nil && !os.IsExist(err) {
			return fmt.Errorf("failed to create patches directory in %s: %w", plan.overlayDir, err)
		}
	} else if !st.IsDir() {
		return fmt.Errorf("patches in %s is not a directory: %w", plan.overlayDir, ErrManifestNotRegular)
	}

	for _, patch := range plan.patches {
		relPath := filepath.Join("patches", patch.fileName)
		f, err := root.OpenFile(relPath, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0600)
		if err != nil {
			return fmt.Errorf("failed to open patch file %s in %s: %w", relPath, plan.overlayDir, err)
		}
		if _, err := io.WriteString(f, patch.updatedContent); err != nil {
			_ = f.Close()
			return fmt.Errorf("failed to write patch file %s: %w", relPath, err)
		}
		if err := f.Close(); err != nil {
			return fmt.Errorf("failed to close patch file %s: %w", relPath, err)
		}
	}

	if plan.updatedKust != plan.originalKust {
		f, err := root.OpenFile(plan.kustFileName, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0600)
		if err != nil {
			return fmt.Errorf("failed to open %s in %s: %w", plan.kustFileName, plan.overlayDir, err)
		}
		if _, err := io.WriteString(f, plan.updatedKust); err != nil {
			_ = f.Close()
			return fmt.Errorf("failed to write %s: %w", plan.kustFileName, err)
		}
		if err := f.Close(); err != nil {
			return fmt.Errorf("failed to close %s: %w", plan.kustFileName, err)
		}
	}

	return nil
}
